UNIT_MAP = {'m2': 'm2', 'm3': 'm3', 'kg': 'kg', 't': '吨', '吨': '吨',
            '块': '块', '根': '根', '个': '个', '套': '套', 'm': 'm',
            '张': '张', '桶': '桶', '包': '包'}
SECTIONS = {'主体', '装修', '铝方通', '门', '胶', '石材'}
PROJECT = '丹江口片区'


def first_num(s):
    m = re.search(r'\d+(?:\.\d+)?', s or '')
    return float(m.group()) if m else None


records = []
section = ''
for line in RAW.strip().split('\n'):
    cells = [c.strip() for c in line.split('\t')]
    if not any(cells):
        continue
    head = cells[0]
    # 分节行（如"主体"、"装修"）：首格有字、其余为空
    if head in SECTIONS:
        section = head
        continue
    if len(cells) < 3:
        continue
    name = cells[1]
    unit_raw = cells[2]
    labor = cells[3] if len(cells) > 3 else ''
    mat = cells[4] if len(cells) > 4 else ''
    note = cells[5] if len(cells) > 5 else ''
    if not name:
        continue
    u = UNIT_MAP.get(unit_raw.lower(), unit_raw)
    for price, ctype in ((labor, '人工'), (mat, '材料')):
        amt = first_num(price)
        if amt is None:
            continue
        if '元' in price:  # 价格里已自带单位/说明，不再追加列单位
            content = '%s，%s%s' % (name, ctype, price)
            m_u = re.search(r'元/([^\s（(]+)', price)
            unit_val = ('元/' + m_u.group(1)) if m_u else ('元/' + u)
        else:
            content = '%s，%s%s元/%s' % (name, ctype, price, u)
            unit_val = '元/%s' % u
        records.append({
            'content': content,
            'cost_type': ctype,
            'amount': amt,
            'unit': unit_val,
            'project': PROJECT,
            'feature': section,
            'note': note,
            'tax_mode': '不含税',
            'source': '导入',
        })

out = {'project': PROJECT, 'note': '丹江口片区 实际成本（不含税）', 'records': records}
with io.open('丹江口片区价格数据.json', 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=1)

print('生成记录数:', len(records))
print('按类型:', dict(Counter(r['cost_type'] for r in records)))
print('按分部:', dict(Counter(r['feature'] for r in records)))
